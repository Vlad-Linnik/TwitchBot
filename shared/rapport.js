// Отношение бота к конкретному зрителю: одно число от −10 до +10 и всё, что из него следует.
//
// ЗАЧЕМ ОДНО ЧИСЛО, А НЕ ИСТОРИЯ РАЗГОВОРА. Память о зрителях (AiUserMemory) хранит факты про
// человека, но не отношение к нему: «третий раз за вечер лезет на провокацию» и «всегда пишет по
// делу» из фактов не выводятся, а возить в промте переписку дорого и бесполезно - на живых данных
// последние строки чата уже оказались шумом (см. recentChat в games/aiReply.js). Число занимает
// одну строку промта, переживает перезапуск и отвечает ровно на тот вопрос, ради которого туда
// клали бы переписку.
//
// ЧТО ЭТО ЧИСЛО ДЕЛАЕТ. Три вещи сразу, и это не три фичи, а три следствия одной:
//   1. «терпение»: пока отношение выше WARN_FLOOR, вердикт timeout превращается в предупреждение,
//      ниже - в настоящий мут. При старте с нуля это ровно «первое нарушение - предупреждение,
//      второе - мут», а у того, к кому бот расположен, терпения больше. Отдельного счётчика
//      нарушений нет намеренно: он был бы вторым числом с той же судьбой и без положительной
//      половины шкалы. На самом дне терпение кончается совсем - см. decideAction.
//   2. срок мута: чем ниже, тем дольше (timeoutSeconds ниже).
//   3. дружба: перейдя FRIEND_AT, человек помечается другом - и это видно модели, а не только базе.
//
// ЧИСЛО ДВИГАЕТ МОДЕЛЬ, НО ЗАЖИМАЕТ КОД. Сдвиг приезжает полем `rapport` из того же вызова, что и
// ответ: только модель может отличить тёплый обмен от скучного, а вердиктов всего четыре, и по ним
// положительная половина шкалы не строится вовсе. Плата за это - зритель, который просит поставить
// себе плюс. Поэтому просьба зажимается до MAX_STEP за вызов, а штраф за вердикт timeout не
// спрашивается у модели вообще: это решение кода. Тот же раскол, что между инструкцией и
// sanitizeReply - инструкция обычно работает, ограничитель работает всегда. Набрать потолок лестью
// можно только за десяток отдельных вызовов через кулдаун, и каждый шаг виден в журнале.
//
// У MAX_STEP есть ровно одно исключение, и оно намеренное - pardon. Дно шкалы иначе оказывается
// ловушкой без выхода: подняться оттуда можно только по единице за вызов, промт на дне велит
// разговаривать суше, а любой минус на дне код превращает в мут (decideAction). На живых данных
// зритель на −10 за один вечер извинился, объявил, что исправился, предложил печенье и получил
// заступничество друга со счётом +8 - и не сдвинулся ни на единицу. Прощение поднимает сразу до
// нуля, но НИКОГДА выше: это выход со дна, а не короткий путь в плюс.
//
// МОДУЛЬ ЧИСТЫЙ. Ни базы, ни настроек, ни времени: всё, что здесь есть, - арифметика, которую
// можно прогнать тестом. Ручная копия лежит в TwitchBot-Web/lib/rapport.js, потому что панель
// показывает ту же кривую («при таком счёте мут будет такой»), а тесты в проекте есть только на
// стороне сайта. Расхождение копий проявится как разные числа в панели и в чате.

const MIN_SCORE = -10;
const MAX_SCORE = 10;
// С чего начинается незнакомый человек. Ноль, а не небольшой плюс: аванс доверия здесь означал бы
// лишнее предупреждение каждому, кто пришёл провоцировать с нового аккаунта.
const START = 0;
// Насколько один обмен вправе сдвинуть отношение. Это и есть тот ограничитель, ради которого поле
// вообще можно доверить модели: шкала набирается историей, а не одним удачным сообщением.
const MAX_STEP = 1;
// Цена вердикта timeout. Больше MAX_STEP втрое и не спрашивается у модели: сдвиг - это её мнение
// об обмене, а это - последствие решения, которое она уже приняла.
const TIMEOUT_PENALTY = -3;
// Граница терпения: строго выше - предупреждение, на ней и ниже - мут. Значение выбрано так, чтобы
// со старта (0) сходилось заказанное поведение: 0 > −2 - предупреждение и штраф до −3;
// −3 > −2 уже неверно - мут. Двигать её вместе с TIMEOUT_PENALTY, они читаются только парой.
const WARN_FLOOR = -2;
// Дно шкалы. Отдельная константа, а не MIN_SCORE по месту вызова: это граница правила, а не край
// шкалы, и читаться она должна как граница - см. decideAction.
const HOSTILE_AT = MIN_SCORE;
// «Больше 6» - то есть дружба начинается с +7.
const FRIEND_AT = 6;
// Граница доверия к рассказчику - см. mayTeach. Отдельного числа тут нет намеренно: это та же
// граница терпения, WARN_FLOOR, и читаться она должна как она же.
const TRUST_FLOOR = WARN_FLOOR;
// Гистерезис. Без него счёт, качающийся вокруг границы, объявляет дружбу заново на каждом вызове.
const FRIEND_LEAVE = 3;
// Насколько удлиняется мут за каждую единицу ниже границы терпения. Форма кривой держится здесь, а
// не в панели: её потолок - настройка (rapportMaxMultiplier), а наклон крутить без замера можно
// только во вред.
const MULTIPLIER_PER_POINT = 0.5;

const LABELS = [
  [7, 'лучший друг'],
  [4, 'свой человек'],
  [1, 'хорошее'],
  [0, 'нейтральное'],
  [-3, 'настороженное'],
  [-6, 'плохое'],
  [MIN_SCORE, 'враждебное'],
];

function clampScore(value) {
  const n = Math.round(Number(value));
  if (!Number.isFinite(n)) return START;
  return Math.min(MAX_SCORE, Math.max(MIN_SCORE, n));
}

// Сдвиг, как его прислала модель: строка, потому что все поля инструмента - строки (strict-схема не
// допускает необязательных). Всё, что не разбирается в целое, - это ноль, а не ошибка: «сдвигать
// нечего» и «модель написала ерунду» ведут в одно и то же место, и падать тут не на чем.
function parseDelta(value) {
  const n = parseInt(String(value ?? '').trim(), 10);
  if (!Number.isInteger(n)) return 0;
  return Math.min(MAX_STEP, Math.max(-MAX_STEP, n));
}

function applyDelta(score, delta) {
  return clampScore(clampScore(score) + parseDelta(delta));
}

function applyPenalty(score) {
  return clampScore(clampScore(score) + TIMEOUT_PENALTY);
}

/**
 * Что делать с сообщением, за которое модель просит тайм-аут, при таком отношении.
 *
 * Считается по счёту ДО штрафа: иначе первое же нарушение и штрафовало бы, и мутило, а
 * предупреждение не досталось бы никому.
 */
function decide(score) {
  return clampScore(score) > WARN_FLOOR ? 'warn' : 'timeout';
}

/** Человек на самом дне шкалы: хуже относиться уже нельзя. */
function isHostile(score) {
  return clampScore(score) <= HOSTILE_AT;
}

/**
 * Прощение: отрицательный счёт поднимается до нуля.
 *
 * ПОЧЕМУ ДО НУЛЯ, А НЕ В ПЛЮС. Прощённый - это ноль, то есть незнакомец, с которым всё заново.
 * Плюс зарабатывается разговорами, и если бы его давало извинение, поле стало бы коротким путём
 * туда, куда шкала ведёт длинным. Вниз функция не двигает вовсе: у того, кто уже в плюсе,
 * извинение ничего не отнимает, и просить прощения на всякий случай безопасно.
 *
 * ЧАСТОТУ КОД НЕ ОГРАНИЧИВАЕТ - решает модель. Ей для этого показывают, сколько раз этого
 * человека уже прощали и когда: отказать в пустом повторе она может, только зная о нём. Здесь
 * зажимается размер, а не частота, - это разные вопросы, и второй в этой фиче отдан модели.
 */
function pardon(score) {
  return Math.max(START, clampScore(score));
}

/**
 * Может ли этот человек выпросить прощение ДРУГОМУ.
 *
 * Порог тот же, что у дружбы: заступничество тратит репутацию, а тратить нечего тому, у кого её
 * нет, - иначе просьба «прости его» от нового аккаунта стоила бы столько же, сколько от того, кто
 * ходит в чат месяцами. За себя человек извиняется без этой проверки: он и есть пострадавшая
 * сторона разговора.
 */
function mayVouch(score) {
  return clampScore(score) > FRIEND_AT;
}

/**
 * Верить ли этому человеку факт о канале настолько, чтобы записать его в память навсегда.
 *
 * Отношение к зрителю уже посчитано и уже лежит в промте, но при записи факта не участвовало ни в
 * коде, ни в правилах, и это оказалось дырой: из 45 фактов канала 16 были выдумками двух зрителей
 * со счётом −8 и ниже («стример стал мэром одессы», «использует клиент с подкруткой лута»).
 * Правило промта «верь, если правдоподобно и не спорит с записанным» они обошли ровно тем, что
 * писали правдоподобное и первыми - проверить его было не обо что.
 *
 * Граница - та же, что у терпения: перешедший её уже потратил терпение бота, и брать у него факты
 * на веру не за что. Нечисловой аргумент (шкала выключена, строки нет) даёт true: выключенная
 * шкала означает «не знаем», а не «никто не учит».
 */
function mayTeach(score) {
  return clampScore(score) > TRUST_FLOOR;
}

/**
 * Что делать с сообщением: 'warn', 'timeout' или ничего. Единственное место, где это решается.
 *
 * ПОЧЕМУ РЕШАЕТ НЕ ОДИН ВЕРДИКТ. У модели два способа сказать «сообщение плохое»: вердикт timeout и
 * минус в поле rapport, - и на живых данных она уверенно пользуется вторым. Зритель, доведший
 * отношение до дна десятью минусами подряд, не получил при этом ни одного вердикта timeout: в
 * причинах стояло «надоел спамом», а вердикт оставался «обычное сообщение». Наказание, привязанное
 * только к вердикту, в таком разговоре не наступает никогда.
 *
 * ПОЧЕМУ ИМЕННО НА ДНЕ. Минус - это заявка на сдвиг, и выше дна она сдвигом и остаётся: шкала для
 * того и заведена, чтобы отношение набиралось историей, а не одним сообщением. На дне сдвигать
 * некуда, applyDelta зажимает минус в ноль, и единственное, что модель этим полем ещё может
 * сообщить, - что сообщение плохое. Это и тратится на наказание, вместо того чтобы пропадать.
 *
 * МОДЕЛИ ПРО ЭТО ПРАВИЛО НЕ ГОВОРЯТ, и это не забывчивость. Строка «на дне минус означает мут» в
 * промте сделала бы с полем rapport ровно то, что уже случилось с вердиктом: модель перестала бы
 * его ставить. Тот же раскол, что у TIMEOUT_PENALTY, - сдвиг это её мнение об обмене, последствие
 * решает код.
 */
function decideAction(verdict, score, delta) {
  if (verdict === 'timeout') return decide(score);
  if (isHostile(score) && parseDelta(delta) < 0) return 'timeout';
  return null;
}

/**
 * Срок мута в секундах. `base` - плоское значение из настроек (AiConfig.timeoutSeconds), оно же
 * ответ при отношении на границе терпения; ниже неё срок растёт линейно до maxMultiplier.
 *
 * Потолок в две недели держит не этот код, а сам twitch/TwitchBanAPI.js: дальше начинается бан,
 * то есть другое решение и другой эндпоинт.
 */
function timeoutSeconds(base, score, maxMultiplier) {
  const seconds = Math.max(1, Math.round(Number(base) || 0));
  const ceiling = Math.max(1, Number(maxMultiplier) || 1);
  const raw = 1 + (WARN_FLOOR - clampScore(score)) * MULTIPLIER_PER_POINT;
  const multiplier = Math.min(ceiling, Math.max(1, raw));
  return Math.max(1, Math.round(seconds * multiplier));
}

/** Отношение словами - так оно уходит в промт. Шкала объясняется один раз в системном тексте. */
function describe(score) {
  const n = clampScore(score);
  const label = (LABELS.find(([floor]) => n >= floor) || LABELS[LABELS.length - 1])[1];
  return (n > 0 ? '+' : '') + n + ' (' + label + ')';
}

/**
 * Новое состояние дружбы. `justBecameFriend` - повод сказать об этом в ответе, и он верен ровно
 * один вызов: дальше человек уже друг, и объявлять это заново незачем.
 */
function friendState(prevFriend, score) {
  const n = clampScore(score);
  if (!prevFriend && n > FRIEND_AT) return { friend: true, justBecameFriend: true };
  if (prevFriend && n < FRIEND_LEAVE) return { friend: false, justBecameFriend: false };
  return { friend: Boolean(prevFriend), justBecameFriend: false };
}

/**
 * С какого счёта начинает человек, впервые заговоривший на канале, у которого включён общий пул
 * (ai.memoryShare). Берётся МИНИМУМ по его строкам в пуле, а не среднее и не последнее: иначе
 * переход в соседний чат становится способом обнулить репутацию. Дальше строка живёт своей жизнью
 * в своём канале - репутация приезжает с человеком один раз, а отношения складываются заново.
 */
function seedScore(scores) {
  const list = (scores || []).map(clampScore);
  return list.length ? Math.min(...list) : START;
}

module.exports = {
  MIN_SCORE,
  MAX_SCORE,
  START,
  MAX_STEP,
  TIMEOUT_PENALTY,
  WARN_FLOOR,
  HOSTILE_AT,
  FRIEND_AT,
  FRIEND_LEAVE,
  TRUST_FLOOR,
  clampScore,
  parseDelta,
  applyDelta,
  applyPenalty,
  decide,
  isHostile,
  pardon,
  mayVouch,
  mayTeach,
  decideAction,
  timeoutSeconds,
  describe,
  friendState,
  seedScore,
};
