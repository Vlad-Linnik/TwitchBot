// Выбор того, что бот берёт из своей памяти в конкретный запрос: по словам вопроса, а не всё
// подряд.
//
// ЗАЧЕМ. Каждый факт из AiChannelMemory уходит во ВХОДНЫЕ токены каждого платного вызова по
// этому каналу, поэтому «сколько фактов помним» и «сколько фактов читаем» раньше были одним и
// тем же числом: потолок памяти был потолком расхода. Отбор разрывает эту связь - хранилище
// растёт, а в запрос уходит фиксированная горстка, так что память можно увеличить, не увеличив
// счёт.
//
// ПОЧЕМУ СТЕММЕР, А НЕ СРАВНЕНИЕ СТРОК. Русский язык словоизменительный: «стрима», «стримы»,
// «стримом» обязаны схлопываться на «стрим», иначе вопрос «когда стримы?» не найдёт факт,
// записанный как «стрим начинается в 19:00». shared/russianStemmer.js - тот же ручной порт
// Snowball, что уже мерялся в этом проекте на настоящих логах канала.
//
// ПОЧЕМУ СТЕМЫ НЕ ХРАНЯТСЯ В MONGO. Их можно было бы записывать в строку при добавлении факта
// и искать через $in, но тогда: (1) строки, добавленные руками на сайте, остались бы без стемов
// (сайт этот модуль не импортирует - репозитории не видят друг друга), (2) потребовалась бы
// разовая миграция уже записанных фактов, (3) появилась бы ещё одна ручная копия, которой
// нельзя разъезжаться. Разбор двух сотен коротких фактов - доли миллисекунды, а происходит он
// уже после того, как ответ зрителю ушёл в чат. Считаем на месте.
//
// ПОРОГОВ ЗДЕСЬ РОВНО ОДИН И ОН НЕ СТРАШЕН. Отбор фактов порога не имеет вовсе - берём лучшие
// N по баллу. Порог есть только у поиска похожего вопроса (findSimilarAnswer), и цена ошибки
// там намеренно низкая: находка идёт в промт ПОДСКАЗКОЙ, которую модель вольна не принять, а
// не готовым ответом зрителю. Точное совпадение по-прежнему обслуживает db/aiStore.js без
// обращения к модели - здесь только «кажется, об этом уже спрашивали».
const { stem } = require('./russianStemmer.js');
const { STOPWORDS } = require('./textStats.js');

// Короче трёх букв стем не несёт смысла ("дом" - предел), длиннее тридцати - это не слово.
const MIN_STEM_LENGTH = 3;
const MAX_STEM_LENGTH = 30;
// Сколько слов вопроса вообще рассматривается. Стена текста не должна превращаться в отбор по
// сотне ключей: смысл вопроса всё равно в первых словах.
const MAX_QUERY_STEMS = 24;
// Совпадение «по началу слова». Snowball оставляет разные стемы у разных форм одного слова
// («игра» -> игр, «играет» -> игра), и без этого правила вопрос «во что играем» не находил бы
// факт про игру. Хвост ограничен одной буквой ровно поэтому: остаток словоизменения - это
// гласная, а не слог, и без ограничения «бан» начал бы матчить «банан». Балл неполный: «пар» и
// «парк» тоже отличаются одной буквой, и стоить это должно дешевле прямого попадания.
const PREFIX_MATCH_MIN = 3;
const PREFIX_MATCH_MAX_EXTRA = 1;
const PREFIX_MATCH_WEIGHT = 0.6;

// Сколько слов для поиска модель может привесить к факту сверх его собственного текста. Это
// потолок, а не настройка: им и ограничена та широта, которую делитель в rankFacts намеренно не
// считает, - см. factStems.
const MAX_FACT_KEYWORDS = 5;

// Стоп-слова сравниваются по стему, а не по написанию: список в textStats.js перечисляет
// «какой», а в чате встретится «какие» - один стем, одно решение.
const STOPWORD_STEMS = new Set();
for (const word of STOPWORDS) {
  const s = stem(word);
  if (s) STOPWORD_STEMS.add(s);
}

// --- вес факта по автору ----------------------------------------------------------------------
//
// Учить бота может кто угодно - это решение владельца, и оно не про то, кого пускать, а про то,
// сколько стоит чьё слово. Написанное админом руками и сказанное самим стримером про свой канал
// весит больше слова случайного зрителя, и вес работает в трёх местах сразу: в промте у факта
// видна его роль (при противоречии модель предпочтёт авторитетный), при отборе под вопрос он
// идёт выше при равном совпадении, при переполнении первым вылетает факт от зрителя.
//
// Ноль для зрителя - не «не верим», а «при прочих равных уступает». Строки, записанные до
// появления этого поля, попадают сюда же: у них автора не спрашивали.
const FACT_PRIORITY = { admin: 3, broadcaster: 3, moderator: 2, vip: 1, viewer: 0 };
const FACT_ROLE_LABELS = {
  admin: 'добавлено вручную',
  broadcaster: 'со слов стримера',
  moderator: 'со слов модератора',
  vip: 'со слов VIP',
  viewer: 'со слов зрителя',
};

function factPriority(row) {
  if (!row) return 0;
  if (row.source === 'admin') return FACT_PRIORITY.admin;
  return FACT_PRIORITY[row.authorRole] ?? FACT_PRIORITY.viewer;
}

function factRoleLabel(row) {
  if (!row) return FACT_ROLE_LABELS.viewer;
  if (row.source === 'admin') return FACT_ROLE_LABELS.admin;
  return FACT_ROLE_LABELS[row.authorRole] || FACT_ROLE_LABELS.viewer;
}

/** Значимые стемы текста, без повторов, в порядке появления. */
function stemsOf(text) {
  const out = [];
  const seen = new Set();
  const source = String(text || '').toLowerCase().replace(/ё/g, 'е');
  for (const m of source.matchAll(/[\p{L}\p{N}]+/gu)) {
    const word = m[0];
    if (word.length < MIN_STEM_LENGTH || word.length > MAX_STEM_LENGTH) continue;
    // «@ник» - адресат, а не тема. Обращение к боту из вопроса вырезается ещё до сюда, но
    // упоминание третьего человека остаётся, и без этой проверки чужой ник весил бы в отборе
    // столько же, сколько слово, ради которого вопрос задан.
    if (m.index > 0 && source[m.index - 1] === '@') continue;
    const s = stem(word);
    if (!s || s.length < MIN_STEM_LENGTH) continue;
    if (STOPWORD_STEMS.has(s)) continue;
    // Голое число ключом не бывает: «2026» одинаково стоит в вопросе про год и в любом счёте.
    if (!/\p{L}/u.test(s)) continue;
    if (seen.has(s)) continue;
    seen.add(s);
    out.push(s);
  }
  return out;
}

// Слова, по которым факт вообще может найтись: его собственные плюс те, что модель привесила к
// нему при записи (поле keywords).
//
// ЗАЧЕМ ОНИ. Факт записывается одной формулировкой, а спрашивают его другой. «Стрим начинается в
// 19:00» и «во сколько ты сегодня начнёшь» не пересекаются ни одним словом, и стеммер тут не
// помогает: это синонимы, а не словоформы, и подтянуть их неоткуда - словаря синонимов у нас нет.
// Придумать их может тот, кто факт записывал, поэтому список приходит из той же модели и в том же
// вызове, что и сам факт: отдельный вызов ради пяти слов стоил бы дороже, чем весь отбор экономит.
//
// ДЕЛИТЕЛЬ В rankFacts ИХ НЕ СЧИТАЕТ, и это не забывчивость. Делитель наказывает СЛУЧАЙНУЮ широту:
// длинный факт задевает много слов просто потому, что он длинный. Ключевые слова - широта
// намеренная, и ограничивает её потолок MAX_FACT_KEYWORDS, а не делитель. Считай мы их в делителе,
// факт с ключевыми словами проигрывал бы по своему же прямому попаданию - то есть правка иногда
// ухудшала бы поиск, а это худший из двух перекосов: незаметный.
function factStems(row) {
  const own = stemsOf(row && row.fact);
  const seen = new Set(own);
  const extra = [];
  const keywords = row && Array.isArray(row.keywords) ? row.keywords : [];
  for (const word of keywords.slice(0, MAX_FACT_KEYWORDS)) {
    for (const s of stemsOf(word)) {
      if (seen.has(s)) continue;
      seen.add(s);
      extra.push(s);
    }
  }
  return { own, all: own.concat(extra) };
}

// Два стема - формы одного слова. Единственное место, где это решается: и подсчёт совпадений
// ниже, и проверка «тот же самый вопрос» обязаны понимать одинаково, иначе вопрос мог бы
// считаться тем же самым по одному правилу и не тем же по другому.
function isPrefixVariant(a, b) {
  const [short, long] = a.length <= b.length ? [a, b] : [b, a];
  if (short.length < PREFIX_MATCH_MIN) return false;
  if (long.length - short.length > PREFIX_MATCH_MAX_EXTRA) return false;
  return long.startsWith(short);
}

// Сколько стемов вопроса нашлось в наборе стемов документа. Точное совпадение - балл, совпадение
// по началу более длинного слова - неполный: «игр» и «игра» почти наверняка об одном, но «пар»
// и «парк» - уже нет, и цена этой разницы не должна быть равна цене прямого попадания.
function overlap(queryStems, docStems) {
  const set = new Set(docStems);
  let score = 0;
  let matched = 0;
  for (const q of queryStems) {
    if (set.has(q)) {
      score += 1;
      matched += 1;
      continue;
    }
    let best = 0;
    for (const d of docStems) {
      if (d !== q && isPrefixVariant(q, d)) best = PREFIX_MATCH_WEIGHT;
    }
    if (best) {
      score += best;
      matched += 1;
    }
  }
  return { score, matched };
}

/**
 * Ранжирует факты по близости к вопросу и возвращает не больше limit штук.
 *
 * Балл делится на корень из длины факта: длинный факт задевает больше слов просто потому, что
 * он длинный, и без нормировки он вытеснял бы короткий и точный. Корень, а не длина, чтобы
 * развёрнутый факт не оказался наказан сильнее, чем он того стоит.
 *
 * Порядок на выходе - по createdAt, тот же, в котором строки лежат в базе: нумерация фактов в
 * промте это то, на что ссылается поле forget, и она обязана быть предсказуемой.
 */
function rankFacts(question, rows, limit) {
  const list = Array.isArray(rows) ? rows : [];
  if (!limit || limit < 0) return [];
  if (list.length <= limit) return list;

  const queryStems = stemsOf(question).slice(0, MAX_QUERY_STEMS);
  const scored = list.map((row, index) => {
    // Ищем по словам факта И по привешенным к нему ключевым, делим только на длину самого факта -
    // почему именно так, написано у factStems.
    const { own, all } = factStems(row);
    const { score, matched } = queryStems.length ? overlap(queryStems, all) : { score: 0, matched: 0 };
    return {
      row,
      index,
      matched,
      priority: factPriority(row),
      weight: score / Math.sqrt(Math.max(own.length, 1)),
    };
  });

  // Сначала то, что вопрос действительно задел, потом добивка свежими. Добивка не бесплатная
  // роскошь: в запрос всё равно уходит ровно limit фактов, а свежий факт - лучшее, что можно
  // положить в оставшееся место, когда вопрос не совпал ни с чем.
  // Сначала попадание в вопрос, и только при равном попадании - вес автора. Наоборот было бы
  // хуже: авторитетный, но не относящийся к делу факт вытеснил бы точный ответ на заданный
  // вопрос. Вес решает спор между одинаково подходящими, а не подменяет собой подходящесть.
  scored.sort((a, b) => {
    if (b.weight !== a.weight) return b.weight - a.weight;
    if (b.priority !== a.priority) return b.priority - a.priority;
    return b.index - a.index;
  });

  return scored
    .slice(0, limit)
    .sort((a, b) => a.index - b.index)
    .map((s) => s.row);
}

// --- «об этом уже спрашивали» ---------------------------------------------------------------

// Порог похожести двух вопросов. Мера - коэффициент Дайса: удвоенное число совпавших слов на
// сумму длин. Симметричная, и лишнее слово в одном из вопросов не обваливает её так, как деление
// на длину более длинного: «во сколько сегодня начнётся стрим» против «во сколько начинается
// стрим» - это 0,57, хотя вопрос тот же самый (стеммер не сводит «начнётся» и «начинается» -
// у Snowball это разные основы, и порогом это не лечится).
//
// ПОРОГ НАМЕРЕННО МЯГКИЙ, и вот почему это допустимо. Ошибка в обе стороны стоит здесь разного.
// Пропуск - это молча не сработавшая подсказка. Ложная находка - это одна строка контекста с
// прошлым вопросом И прошлым ответом; модель видит оба текста, а правило в промте прямо велит
// ответить на заданный вопрос, если прошлый оказался о другом. При таком перекосе цен строгий
// порог покупает не ту сторону. Известный пример, который проходит: «сколько лет стримеру»
// против «сколько тебе лет» (0,67) - разные вопросы, отсеивать их приходится уже модели.
//
// Проверять это на живых данных надо колонкой similarTo в журнале ответов: другого зеркала у
// нестрогого сравнения нет.
const SIMILAR_MIN_RATIO = 0.55;
// Одного общего слова мало: «какая игра» и «какая карта» разошлись бы в одном слове из двух.
const SIMILAR_MIN_MATCHED = 2;

// «Тот же самый вопрос»: у обоих один и тот же НАБОР значимых слов, с точностью до порядка,
// словоформы и мусорных слов. Это не подобранное число, а правило, и в нём весь смысл - на такой
// находке ответ отдаётся вообще без обращения к модели, а значит она должна быть объяснима одной
// фразой, а не порогом.
//
// По сути это расширение того же допуска, что уже есть в shared/aiTextKey.js. Тот приводит вопрос
// к ключу по регистру и пробелам и на точном совпадении отвечает бесплатно; здесь к тому же
// допуску добавляются порядок слов, словоформа и слова, не несущие смысла. «Какие фильтры
// используешь» и «какой фильтр ты используешь» - один вопрос. «Во сколько СЕГОДНЯ начнётся стрим»
// и «во сколько начинается стрим» - уже нет: лишнее значимое слово может менять вопрос, и такие
// случаи уходят в подсказку модели ниже, а не в бесплатный ответ.
function coversAll(from, to) {
  return from.every((a) => to.some((b) => a === b || isPrefixVariant(a, b)));
}

function isSameQuestion(aStems, bStems) {
  if (!aStems.length || !bStems.length) return false;
  return coversAll(aStems, bStems) && coversAll(bStems, aStems);
}

/**
 * Ищет в уже отвеченных вопросах канала тот, что по словам совпадает с текущим. Возвращает
 * { text, answer, ratio, same } или null.
 *
 * `same: true` означает «это тот же вопрос другими словами» - вызывающий вправе отдать прошлый
 * ответ и не платить за вызов. `same: false` - только похоже; такая находка идёт в промт
 * подсказкой, и цена ошибки там одна строка контекста, которую модель вправе отбросить. Два
 * разных ответа на один вопрос дают два разных права, поэтому и возвращаются они одним полем, а
 * не двумя вызовами по разным порогам.
 *
 * Строка с точным совпадением набора слов побеждает любую другую, даже если у той выше доля
 * общих слов: доля - оценка похожести, совпадение набора - утверждение о тождестве.
 */
function findSimilarAnswer(question, rows) {
  const queryStems = stemsOf(question).slice(0, MAX_QUERY_STEMS);
  if (queryStems.length < SIMILAR_MIN_MATCHED) return null;

  let best = null;
  for (const row of rows || []) {
    if (!row || !row.answer) continue;
    const docStems = stemsOf(row.text);
    if (!docStems.length) continue;

    if (isSameQuestion(queryStems, docStems)) {
      return { text: row.text, answer: row.answer, ratio: 1, same: true };
    }

    const { score, matched } = overlap(queryStems, docStems);
    if (matched < SIMILAR_MIN_MATCHED) continue;
    // Считается по баллу, а не по числу совпавших: совпадение по началу слова весит меньше и
    // здесь, иначе порог обходился бы парой «пар»/«парк».
    const ratio = (2 * score) / (queryStems.length + docStems.length);
    if (ratio < SIMILAR_MIN_RATIO) continue;
    if (!best || ratio > best.ratio) best = { text: row.text, answer: row.answer, ratio, same: false };
  }
  return best;
}

