// Что из ответа модели годится в вечную заготовку AiAnswerCache, а что нет.
//
// ЗАЧЕМ ЭТО ОТДЕЛЬНО ОТ ПОЛЯ cacheable. Модель сама помечает ответ как eternal или temporary, и
// это её мнение о фактах в ответе. Но на живых данных кэш оказался мёртвым: 2 попадания на 246
// обращений за день, 92% ответов помечены temporary. Причина не в модели, а в том, что две
// настройки гасили друг друга. Характер (AiConfig.persona) заставляет бота почти всегда
// заканчивать встречным вопросом («а ты как думаешь?», «расскажешь?»), а описание поля cacheable
// прямым текстом объявляло такой ответ временным - переиспользованное любопытство выглядит
// фальшиво, и это правда. Но выбрасывать из-за хвоста ВЕСЬ ответ незачем: факт в нём durable,
// временный только хвост. Здесь хвост отрезается, а решение про факты остаётся за моделью.
//
// ЭТО ОГРАНИЧИТЕЛЬ, А НЕ ИНСТРУКЦИЯ. Тот же раскол, что у sanitizeReply и rapport: правило,
// которое должно выполняться всегда, стоит в коде после модели, а не в промте до неё. Поэтому
// пункт про встречный вопрос из описания cacheable убран - код теперь снимает хвост сам.
//
// МОДУЛЬ ЧИСТЫЙ: ни базы, ни настроек, ни времени. Ручная копия лежит в
// TwitchBot-Web/lib/cacheableAnswer.js - исключительно ради тестов, на стороне бота их негде
// запустить. Панель этот модуль не использует; расхождение копий проявится только как разошедшиеся
// тесты, поэтому править обе.

// Сколько должно остаться после отрезания хвоста, чтобы это ещё было ответом. Совпадает с
// MIN_FIXED_ANSWER_CHARS в games/aiReply.js по смыслу: заготовка короче нескольких букв - это не
// ответ, а мусор, который будет отвечать вечно.
const MIN_CACHEABLE_CHARS = 5;

// Границы, по которым отрезается хвост. Кроме конца предложения сюда входит тире-вставка: в живой
// речи встречный вопрос часто прицепляется к утверждению через тире и отдельным предложением не
// становится - «обожаю пиццу с грибами — а какая твоя любимая?». Без этой границы такой ответ
// пришлось бы выбрасывать целиком, а он на три четверти состоит из факта.
//
// Конец предложения требует пробела после себя, поэтому финальный «?» разделителем не считается и
// остаётся внутри последнего сегмента - именно по нему хвост и опознаётся.
const BOUNDARY = /([.!?…]+[)"'»]*\s+|\s+[—–-]\s+)/u;

// Одно слово без знаков препинания - столько занимает смайлик из набора канала, и ничего больше
// осмысленным куском ответа быть не может.
const BARE_TOKEN = /^[\p{L}\p{N}_]{1,15}$/u;

/**
 * Заканчивается ли этот кусок вопросом.
 *
 * После самого «?» бот дописывает закрывающую скобку, кавычку или смайлик из набора канала - всё
 * это ещё хвост, а не начало нового. Поэтому одно короткое слово в конце снимается перед
 * проверкой: «а ты как? xdd» - такой же встречный вопрос, как и без смайлика.
 */
function isQuestion(segment) {
  const text = String(segment == null ? '' : segment)
    .trim()
    .replace(/[)"'»\s]+$/u, '')
    .replace(/\s[\p{L}\p{N}_]{1,15}$/u, '');
  return text.endsWith('?');
}

/**
 * Ответ без встречного вопроса в конце.
 *
 * Хвосты снимаются по одному, пока последний кусок остаётся вопросом: ответ вида «а стоило бы
 * глянуть? Расскажешь, чем цепляет?» состоит из них целиком, и от него не остаётся ничего - это
 * правильный исход, кэшировать там нечего.
 *
 * Возвращает пустую строку, если утверждения не осталось. Пустая строка означает «не кэшировать»,
 * а не «кэшировать пустоту» - вызывающий обязан её проверить.
 */
function withoutTail(text) {
  // split с захватывающей группой даёт [сегмент, разделитель, сегмент, ...]: разделители на
  // нечётных местах, длина всегда нечётная, последний элемент - всегда сегмент.
  const parts = String(text == null ? '' : text).split(BOUNDARY);
  // Смайлик из набора канала, дописанный после «?», разделитель уносит в отдельный кусок:
  // «…играешь» / «? » / «xdd», - и хвост перестаёт опознаваться как вопрос. Склеиваем такой кусок
  // обратно. Склейка безопасна при любом исходе: строка в конце собирается через join, поэтому
  // меняется только разбиение, а не текст.
  while (parts.length > 2 && BARE_TOKEN.test(parts[parts.length - 1].trim())) {
    const token = parts.pop();
    const separator = parts.pop();
    parts[parts.length - 1] += separator + token;
  }
  while (parts.length > 1 && isQuestion(parts[parts.length - 1])) {
    parts.pop();
    const separator = parts.pop();
    // Знак конца предложения уехал В РАЗДЕЛИТЕЛЬ, а принадлежит он сегменту слева, и вернуть его
    // туда обязательно. Иначе ответ, состоящий из двух вопросов подряд («а стоило бы глянуть?
    // Расскажешь, чем цепляет?»), после снятия второго перестаёт опознаваться как вопрос вовсе, и
    // в кэш уходит первый вопрос в виде утверждения.
    parts[parts.length - 1] += separator.trimEnd();
  }
  // Последний оставшийся сегмент проверяется отдельно: разделителя справа у него нет, снимать
  // вместе с ним нечего, а вопросом он быть может - тогда утверждения в ответе нет вообще.
  if (parts.length === 1 && isQuestion(parts[0])) parts.length = 0;
  // Разделитель, оставшийся последним, - это конец предложения или тире, за которыми уже ничего
  // нет. Точку и восклицательный знак оставляем, висящее тире и запятую убираем: класс ниже
  // намеренно не содержит «.!…», поэтому снимается только то, что осталось висеть.
  const out = parts.join('').replace(/[\s,;:—–-]+$/u, '').trim();
  return out.length >= MIN_CACHEABLE_CHARS ? out : '';
}

/**
 * Обещает ли ответ действие, которое повтор из кэша не выполнит.
 *
 * Признак - непустое поле remember: сообщение чему-то научило бота, и ответ на него говорит
 * «запомню». Из кэша та же строка отвечает вечно, ничего при этом не запоминая. На живых данных
 * это одно из двух попаданий кэша за день: «главное, что надо запомнить про амора…» получило
 * закэшированное «Запомню, что Амор на Марсе просто неудержим».
 *
 * Проверка идёт по полю, а не по тексту ответа: искать в ответе слово «запомню» - это гадать, а
 * поле говорит точно, было действие или нет.
 */
function promisesAction(remember) {
  return String(remember == null ? '' : remember).trim().length > 0;
}

module.exports = {
  MIN_CACHEABLE_CHARS,
  isQuestion,
  withoutTail,
  promisesAction,
};
