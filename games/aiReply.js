// на самом деле уходит в запрос, а не отдельную копию, живущую своей жизнью. Одна идемпотентная
// запись за запуск процесса.
aiStore.publishBuiltinPrompt(SYSTEM_RULES);

// --- text handling ------------------------------------------------------------------------------

function escapeRegExp(value) {
  return String(value).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Сообщение, в котором нет ничего кроме смайликов этого канала -> что ответить. null - не тот
// случай, и сообщение идёт дальше обычным путём.
//
// Регистр сверяется ТОЧНО, и это не строгость ради строгости. Twitch различает AROLF и arolf: в
// whiteList лежит ровно то написание, которое рисуется картинкой, поэтому совпавший токен можно
// вернуть в чат как есть и он гарантированно отрисуется. Написанное строчными - это просто
// слово, и разговаривать с ним надо как со словом.
//
// clean() тот же, которым пользуется статистика: без него невидимая антидубль-набивка Twitch
// (U+034F и родня) остаётся отдельным «токеном», не совпадает ни с одним смайликом, и сообщение
// из одного смайлика уезжает в модель - то есть ровно в тот вызов, которого тут и избегают.
function emoteEcho(channel, text) {
  const tokens = clean(text).trim().split(' ').filter(Boolean);
  if (!tokens.length) return null;
  const echo = [];
  for (const token of tokens) {
    if (!chatStats.isInWhiteList(channel, token)) return null;
    if (echo.length < MAX_ECHO_EMOTES && !echo.includes(token)) echo.push(token);
  }
  return echo.join(' ');
}

// Смайлики канала, написанные в самом вопросе, -> их написания в порядке появления. Пустой массив,
// если смайликов нет.
//
// ЗАЧЕМ. Зритель видит картинки, модель читает текст: «AROLF» приезжает к ней словом, которого нет
// ни в одном словаре, и она принимает его то за ник, то за опечатку и отвечает на выдуманное. Весь
// набор канала в промт не отдать - это несколько сотен строк на каждом вызове, - а назвать те
// несколько, что стоят в этом вопросе, стоит одну строку.
//
// СВЕРКА ТОЧНАЯ И ПО ЦЕЛОМУ ТОКЕНУ - ровно то правило, по которому смайлик рисуется у зрителя (см.
// shared/emoteFix.js): и Twitch, и 7TV разбирают сообщение по пробелам и сравнивают токен целиком,
// с учётом регистра. Поэтому «KEKW,» и «kekw» сюда не попадают, и это не дыра в проверке: там
// зритель видит тот же текст, который читает модель, а подсказка закрывает разрыв между картинкой
// и текстом - где разрыва нет, закрывать нечего.
//
// Это обратная сторона той же задачи, что решает emoteFix в sanitizeReply. Там модель написала имя
// смайлика и его надо привести к написанию, которое нарисуется; здесь смайлик уже нарисован у
// зрителя, и модели надо сказать, что это был он.
function emotesInQuestion(channel, text) {
  const found = [];
  for (const token of clean(text).trim().split(/\s+/)) {
    if (!token || found.includes(token)) continue;
    if (!chatStats.isInWhiteList(channel, token)) continue;
    found.push(token);
    if (found.length >= MAX_NAMED_EMOTES) break;
  }
  return found;
}

function stripBotMention(message) {
  const name = String(botInitInfo.settings['username'] || '').toLowerCase();
  if (!name) return String(message || '').trim();
  return String(message || '')
    .replace(new RegExp('@?' + escapeRegExp(name), 'gi'), ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

// Кто есть в этом разговоре, ник -> { userId, login }. Это БЫСТРАЯ ступень опознания адресата, а
// не единственная: здесь user-id уже под рукой и запрос не нужен. Ник, которого тут нет, ещё не
// выдуман - его ищут в базе, см. resolveSubject.
//
// Автор добавляется последним и перекрывает свою же строку из кольца: там id мог не сохраниться
// (строки, записанные до появления поля), а у автора он есть всегда.
function chatParticipants(userState, lines) {
  const people = new Map();
  for (const line of lines) {
    if (line.userId) people.set(line.login, { userId: String(line.userId), login: line.login });
  }
  const login = String(userState['username'] || '').toLowerCase();
  people.set(login, { userId: String(userState['user-id']), login });
  return people;
}

// Каналы, чья память о зрителях читается вместе с этим. Факт про человека - утверждение про
// человека: «играет на гитаре» верно в любом чате, тогда как «стрим в 19:00» верно ровно в одном,
// поэтому пул есть у памяти о зрителях и нет у памяти канала.
//
// ПУЛ - ЭТО НЕ «ВСЕ КАНАЛЫ БОТА». Канал входит в него, только если у него самого включён
// ai.memoryShare, и делиться своей памятью и читать чужую - одно решение, а не два: канал, который
// читает чужое, но не отдаёт своё, превращает общую память в одностороннюю выгрузку. Умолчание -
// выключено, поэтому подключённый завтра канал ничью память не наследует и свою никуда не отдаёт.
// Это же и есть отличие от общего AiFilter, который пришлось разделять обратно: там границы не
// было вовсе, здесь она есть и её включают руками.
//
// Настройки берутся из того же кэша с фоновым обновлением, что и всё остальное в боте: у канала,
// про который ещё не спрашивали, первые секунды после старта видны умолчания, то есть пул может
// оказаться короче. Цена ошибки - один запрос без чужих фактов, а не неверный ответ.
function memoryPool(channel) {
  if (!channelSettings.getSettings(channel).ai.memoryShare) return [channel];
  const pool = [channel];
  for (const login of Object.keys(botInitInfo.channels)) {
    const other = '#' + login;
    if (other === channel) continue;
    if (channelSettings.getSettings(other).ai.memoryShare) pool.push(other);
  }
  return pool;
}

// Про кого вспоминаем в этом запросе. Сам спрашивающий - всегда, ради него память и заводилась;
// плюс те, кого он назвал в вопросе, чтобы «что ты знаешь про васю» вообще имело ответ. Иначе
// факты про третьих лиц были бы записываемыми, но нечитаемыми до тех пор, пока эти третьи лица
// сами что-нибудь не спросят.
//
// Чужие ограничены: каждый добавленный человек - это его факты во входных токенах каждого такого
// вызова, а называют в вопросе обычно одного.
//
// Ищется человек по всему пулу, а записывается факт по-прежнему только про того, кто есть на этом
// канале (resolveSubject ниже). Асимметрия намеренная: прочитать про завсегдатая соседнего чата -
// это ответить на заданный вопрос, а записать про него отсюда - это завести строку там, где её
// никто не увидит и не оспорит.
async function memorySubjects(pool, question, people, authorLogin) {
  const author = people.get(authorLogin);
  const subjects = author ? [author] : [];
  const seen = new Set(subjects.map((p) => p.userId));
  for (const m of String(question).match(/@?[a-z0-9_]{3,25}/gi) || []) {
    if (subjects.length >= MAX_EXTRA_SUBJECTS + 1) break;
    const login = m.replace('@', '').toLowerCase();
    // Та же лестница, что и при записи: сначала разговор, потом база. Иначе факт про молчащего
    // человека можно было бы записать, но нельзя прочитать, пока он сам не заговорит.
    let person = people.get(login);
    if (!person) {
      try {
        person = await chatStats.findUserByLogin(pool, login);
      } catch (err) {
        person = null;
      }
    }
    if (!person || seen.has(person.userId)) continue;
    seen.add(person.userId);
    subjects.push(person);
  }
  return subjects;
}

// Кто названный в вопросе человек на этом канале - теми же словами, что и роль автора вопроса.
//
// Роль автора приезжает из бейджей его собственного сообщения, то есть это факт. Про третье лицо
// бейджей нет, и спросить некого, кроме списка модераторов в памяти процесса
// (twitch/moderators.js) - Helix отдаёт список модераторов только по токену самого стримера, а его
// у бота нет. Отсюда две поправки, и обе обязательные.
//
// СТРИМЕР В СПИСКЕ НЕ БЫВАЕТ НИКОГДА: Twitch не выдаёт ему события mod, поэтому владелец канала
// проверяется отдельно по id канала (тем же способом, что и в twitch/ActivitiTracker.js).
//
// ПУСТОЙ СПИСОК - ЭТО «НЕ ЗНАЕМ», А НЕ «МОДЕРАТОРОВ НЕТ». Список собран из событий mod/unmod, и про
// модератора, назначенного до первого запуска бота, строки в нём нет. Пока в списке хоть кто-то
// есть, отрицательный ответ имеет цену; на канале с пустым списком роль не называется вовсе, иначе
// бот уверенно объявил бы не модератором каждого, включая настоящих.
function peerRole(channel, userId) {
  const broadcasterId = broadcasterIdOf(channel);
  if (!broadcasterId) return null;
  if (String(userId) === String(broadcasterId)) return ROLE_LABELS.broadcaster;
  if (!moderators.getModerators(broadcasterId).size) return null;
  return moderators.isModerator(broadcasterId, String(userId)) ? ROLE_LABELS.moderator : 'не модератор';
}

// Досье на человека, НАЗВАННОГО В ВОПРОСЕ, - то, чего нет в фактах о нём: отношение бота к нему и
// несколько прошлых разговоров с ним.
//
// «Что думаешь про Васю» - вопрос про отношения, а не про анкету, и одними записанными фактами он
// не отвечается: факты говорят, кто такой Вася, а спрашивают, что бот о нём думает. Оба недостающих
// куска уже собираются на каждом вызове для автора вопроса, разница только в том, про кого их
// читают.
//
// Цена ограничена теми же двумя числами, что и у фактов: названных людей не больше
// MAX_EXTRA_SUBJECTS, разговоров на каждого - PEER_EXCHANGES, то есть меньше, чем у автора.
//
// Отношение попадает в промт, ТОЛЬКО ЕСЛИ СТРОКА ДЕЙСТВИТЕЛЬНО ЕСТЬ. Без неё getRapport возвращает
// засев по пулу (или ноль), то есть мнение, которого бот ещё не составлял, - выдать его за
// «что я о нём думаю» значило бы придумать отношение к незнакомому человеку. Ничего не пишется:
// строка про третье лицо заводится тогда же, когда и раньше, - когда он заговорит сам.
async function peerDossiers(pool, channel, people, cfg) {
  if (!people.length) return [];
  return Promise.all(
    people.map(async (person) => {
      const [exchanges, relation] = await Promise.all([
        aiStore.recentExchanges(channel, person.userId, PEER_EXCHANGES),
        cfg.rapportEnabled
          ? aiStore.getRapport(pool, channel, person.userId, person.login)
          : Promise.resolve(null),
      ]);
      return {
        login: person.login,
        role: peerRole(channel, person.userId),
        exchanges,
        relation: relation && relation.exists ? relation : null,
      };
    })
  );
}

// Ник из поля rememberAbout - в человека, про которого можно завести строку.
//
// Сначала разговор, потом база. Кольцо отвечает без запроса и покрывает обычный случай - человек
// сейчас здесь. Но рассказывают и про тех, кто сегодня молчит, а «его нет в последних пяти
// строках» ничего не говорит о том, существует ли такой ник: это разные вопросы, и второй решается
// поиском в UserIdentities с проверкой, что человек писал именно в этом канале.
//
// Не нашёлся нигде - null, и факт уходит в память канала. Модель могла выдумать ник, а могла
// сказать что-то верное про сообщество, и выбрасывать факт из-за неразобранного адресата дороже,
// чем записать его туда, где его увидит и почистит человек.
async function resolveSubject(channel, name, people) {
  const login = String(name || '').replace('@', '').trim().toLowerCase();
  if (!login) return null;
  const here = people.get(login);
  if (here) return here;
  try {
    return await chatStats.findUserByLogin(channel, login);
  } catch (err) {
    // Недоступная база - это «не смогли проверить», а не «ника не существует». Факт уходит в
    // память канала, то есть туда же, куда и при выдуманном нике: потерять его хуже.
    console.error('[aiReply] subject lookup failed:', err.message);
    return null;
  }
}

function allowedMentionLogins(question, lines) {
  const allowed = new Set();
  const matches = String(question).match(/@?[a-z0-9_]{3,25}/gi) || [];
  for (const m of matches) allowed.add(m.replace('@', '').toLowerCase());
  for (const line of lines) allowed.add(line.login);
  return allowed;
}

// Обстановка для промта: те же строки кольца, приведённые к виду «ник: текст».
//
// ПОСЛЕДНЯЯ СТРОКА - ЭТО САМ ВОПРОС. index.js кладёт в кольцо каждое сообщение до того, как оно
// дойдёт до цепочки команд, поэтому к моменту ответа сообщение, на которое мы отвечаем, уже лежит
// в кольце последним. Показывать его отдельно от вопроса значит показать его дважды и подсказать,
// что зритель написал что-то ещё, - поэтому оно отбрасывается по совпадению автора и текста, а не
// по одной лишь позиции: между записью и ответом кольцо может пополниться, и слепое отбрасывание
// хвоста съело бы тогда чужую строку.
function chatContext(lines, login, message) {
  const out = [];
  const author = String(login || '').toLowerCase();
  const raw = String(message || '');
  for (const line of lines) {
    if (line.login === author && line.text === raw) continue;
    const text = clean(line.text).trim().slice(0, MAX_CHAT_LINE_CHARS);
    if (text) out.push({ login: line.login, text });
  }
  return out;
}

// Applied to what the model produced, not instead of telling it the rules. The instruction is what
// usually works; this is what always works, and on a cheap model the difference shows.
// Обрывок разметки вызова инструмента, а не текст. Слабая модель иногда закрывает параметр прямо
// внутри его значения, и в поле приезжает «</antml_parameter> <parameter name="forget">».
//
// Это не гипотеза: на проде такие строки составили 36 из 58 записанных фактов - больше половины
// памяти канала. В ответах они не всплыли ни разу, но это везение, а не защита: тот же обрывок в
// reply ушёл бы прямо в чат, поэтому чистится и он тоже.
const TOOL_MARKUP = /antml|parameter\s+name\s*=|<\s*\/\s*[\w@$.]*parameter|<\s*\/?\s*(?:function|invoke|tool_use)/i;

// В ответе обрывок всегда идёт хвостом - модель дописывает закрывающие теги после готового
// текста. Поэтому не вырезаем куски из середины, а обрезаем по первому вхождению: всё, что после
// него, уже не предложение, а попытка закрыть параметр.
function stripToolMarkup(text) {
  const at = String(text || '').search(TOOL_MARKUP);
  return at === -1 ? String(text || '') : String(text).slice(0, at);
}

function sanitizeReply(text, allowedLogins, channel) {
  let out = stripToolMarkup(text).replace(/\s+/g, ' ').trim();
  out = out.replace(/https?:\/\/\S+/gi, ' ');
  out = out.replace(/\b[\w-]+\.(?:com|net|org|ru|ua|tv|io|me|gg|xyz|dev|app)\b\S*/gi, ' ');
  // A stray "@nick" would ping a real person who never asked to be involved; the name itself can
  // stay, only the ping is removed.
  out = out.replace(/@([a-z0-9_]{3,25})/gi, (full, login) =>
    allowedLogins.has(login.toLowerCase()) ? full : login
  );
  // A leading "!" or "/" would fire a command - ours, another bot's, or Twitch's own.
  out = out.replace(/^[!/.]+\s*/, '');
  // Смайлики - последними, потому что правка ставит пробелы, а всё выше их схлопывает и режет
  // куски строки. Написанное моделью «kekw,» станет картинкой только если оно написано регистром
  // из набора канала и стоит отдельным токеном - см. shared/emoteFix.js.
  out = emoteFix.fixEmotes(out, (word) => chatStats.canonicalEmote(channel, word));
  return out.replace(/\s+/g, ' ').trim().slice(0, MAX_REPLY_CHARS);
}

// A fact is proposed out of what a viewer wrote, so it is cleaned before it is stored rather than
// on the way out: it will be read back into every later prompt for this channel, and a link or a
// leading command character sitting in the memory is a link or a command in a future reply.
function sanitizeFact(text) {
  // Факт с обрывком разметки не чистится, а отбрасывается целиком. Это не факт с мусором по
  // краям, а артефакт разбора: «спасённый» остаток был бы обрывком чужой мысли, который потом
  // уедет в каждый платный запрос по этому каналу.
  if (TOOL_MARKUP.test(text)) return '';
  const out = String(text || '')
    .replace(/\s+/g, ' ')
    .replace(/https?:\/\/\S+/gi, ' ')
    .replace(/\b[\w-]+\.(?:com|net|org|ru|ua|tv|io|me|gg|xyz|dev|app)\b\S*/gi, ' ')
    .replace(/^[!/.]+\s*/, '')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, MAX_FACT_CHARS);
  return out.length >= MIN_FACT_CHARS ? out : '';
}

// Поисковые слова к факту. Чистятся отдельно от него и заметно строже: в промт они не уходят
// никогда, читает их только стеммер в shared/memoryRecall.js, поэтому от строки нужны слова и
// ничего кроме - ни ссылок, ни знаков, ни ников.
//
// Потолок здесь не отсечение мусора, а та самая цена: каждое слово - это лишний шанс факту
// найтись, и делитель в rankFacts эти шансы намеренно не считает (см. factStems). Ограничивает их
// только это число.
function sanitizeKeywords(text) {
  if (TOOL_MARKUP.test(text)) return [];
  const out = [];
  const seen = new Set();
  // Ссылка вырезается целиком, а не разбирается на слова: «http a ru» - это три мусорных слова,
  // занявших место в потолке, а не поисковое слово, которое кто-то когда-нибудь напишет в чате.
  const source = String(text || '')
    .replace(/https?:\/\/\S+/gi, ' ')
    .replace(/\b[\w-]+\.(?:com|net|org|ru|ua|tv|io|me|gg|xyz|dev|app)\b\S*/gi, ' ');
  for (const part of source.split(/[,;\n]+/)) {
    const word = part
      .toLowerCase()
      .replace(/[^\p{L}\p{N}\s-]/gu, ' ')
      .replace(/\s+/g, ' ')
      .trim()
      .slice(0, MAX_KEYWORD_CHARS);
    // Короче трёх букв стема не даёт вовсе - такое слово всё равно не дошло бы до сравнения.
    if (word.length < 3 || seen.has(word)) continue;
    seen.add(word);
    out.push(word);
    if (out.length >= memoryRecall.MAX_FACT_KEYWORDS) break;
  }
  return out;
}

// Сколько секунд мута выдать по собственной просьбе зрителя, уже с перевыполнением.
//
// Ноль означает «не просил»: всё, что не разбирается в положительное целое, ведёт сюда же, и
// падать тут не на чем. «Забань меня навсегда» - это не число, и не делает ничего: бан и тайм-аут
// разные решения, и второе не умеет притворяться первым.
function selfTimeoutSeconds(value) {
  const asked = parseInt(String(value ?? '').trim(), 10);
  if (!Number.isInteger(asked) || asked < 1) return 0;
  return Math.min(MAX_SELF_TIMEOUT_SECONDS, asked * SELF_TIMEOUT_FACTOR);
}

// Просьба замутить ДРУГОГО человека, как её прислала модель: кого и на сколько.
//
// Срок по умолчанию здесь есть, а адресата по умолчанию нет, и это не мелочь: «замуть его» без
// числа - обычная просьба, «замуть» без ника - не просьба вовсе, и додумывать за модель, кого она
// имела в виду, нечем. Потолок стоит тут же, потому что число из этого поля - пожелание
// просящего, а не решение: выдаёт мут код, значит и ограничивает его код.
function requestedMute(out) {
  const name = String((out && out.muteTarget) || '').replace('@', '').trim().toLowerCase();
  if (!name) return null;
  const asked = parseInt(String((out && out.muteSeconds) || '').trim(), 10);
  const seconds = Number.isInteger(asked) && asked > 0 ? asked : DEFAULT_REQUESTED_MUTE_SECONDS;
  return { name, seconds: Math.min(MAX_REQUESTED_MUTE_SECONDS, seconds) };
}

function sanitizeReason(text) {
  return String(text || '')
    .replace(/\s+/g, ' ')
    .replace(/[@!/]/g, '')
    .trim()
    .slice(0, MAX_TIMEOUT_REASON_CHARS);
}

// Other chat bots must never reach the model. games/duelFromMrCopusBot.js only claims the two
// exact phrases it knows (a duel challenge and a duel result); every OTHER thing mistercopus_bot
// says that happens to mention us would otherwise fall through to here, cost a request, and get
// a nonsense answer aimed at a machine - with a real chance of the two bots answering each other.
//
// Checked by login first and id second: the id set is resolved from Helix at startup and is empty
// if that lookup failed, while the login list is always there.
function isBotSender(userState) {
  const login = String(userState["username"] || "").toLowerCase();
  return KNOWN_BOT_LOGINS.includes(login) || isKnownBot(userState["user-id"]);
}

// Кто спрашивает - одной строкой в промт. Раньше этого не было, и модель не могла отличить
// стримера от случайного зрителя: любая просьба «запомни» выглядела одинаково, а безопасным
// поведением при неизвестном авторе было не запоминать ничего. Роль стоит несколько токенов и
// возвращает решению основание.
// Машинный ключ роли. Он же уезжает в строку памяти: чей это факт - решает, насколько он весит
// при отборе, кто вылетит первым при переполнении и чьему слову модель поверит при противоречии.
// Учить бота по-прежнему может кто угодно, но не всякое слово стоит одинаково.
function roleKey(userState) {
  const badges = userState['badges'] || {};
  if ('broadcaster' in badges) return 'broadcaster';
  if (isMod(userState)) return 'moderator';
  if ('vip' in badges) return 'vip';
  return 'viewer';
}

const ROLE_LABELS = {
  broadcaster: 'стример этого канала',
  moderator: 'модератор канала',
  vip: 'VIP канала',
  viewer: 'зритель',
};

function describeRole(userState) {
  return ROLE_LABELS[roleKey(userState)];
}

// Числовой id канала: он же нужен и статусу эфира, и карточке стрима. Канала может не быть в
// botInitInfo (его добавили на сайте после старта бота) - тогда id нет, и это значит «не в эфире»,
// а не «неизвестно, отвечаем».
function broadcasterIdOf(channel) {
  const entry = botInitInfo.channels[channel.replace('#', '')];
  return entry ? entry.id : null;
}

function isProtected(userState) {
  if (isMod(userState)) return true;
  const badges = userState['badges'];
  return Boolean(badges && 'vip' in badges);
}

// Тот же вопрос, что и isProtected, но про ТРЕТЬЕ ЛИЦО. Бейджи приезжают только в собственном
// сообщении человека, поэтому спросить остаётся тот же список, что и у peerRole, - и он же диктует
// осторожность: пустой список означает «не знаем», а не «модераторов нет». Канала нет в
// botInitInfo - неизвестен и стример, и модераторы, то есть проверить нечем и мутить не за что.
//
// VIP так не проверяется вовсе: списка VIP у бота нет ни в каком виде. Мут VIP-у Twitch разрешает,
// так что молчаливой ошибки здесь не будет, но защиты, симметричной isProtected, у них тоже нет.
// Бот - никогда, и мы сами в том числе: два бота, мутящие друг друга по просьбам зрителей, это не
// шутка, а петля.
function peerProtected(channel, person) {
  const broadcasterId = broadcasterIdOf(channel);
  if (!broadcasterId) return true;
  if (String(person.userId) === String(broadcasterId)) return true;
  if (moderators.isModerator(broadcasterId, String(person.userId))) return true;
  return KNOWN_BOT_LOGINS.includes(person.login) || isKnownBot(person.userId);
}

