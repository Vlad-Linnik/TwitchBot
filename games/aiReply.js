// Synchronous eligibility check. Returning true means "this message is mine, a reply is on its
// way" - the caller must not fall through to the scripted replies. Everything expensive happens
// after the caller has already returned.
function tryAnswer(client, channel, userState, message, scripted) {
  const cfg = aiSettings.get();
  if (!cfg.enabled) return false;
  // Ключ спрашивается у поставщика выбранной модели, а не у одного зашитого имени переменной:
  // ключи у поставщиков свои, и выбранная в панели модель решает, какой из них нужен.
  if (!aiProvider.hasKey(cfg.model)) return false;

  const settings = channelSettings.getSettings(channel);
  if (!settings.ai || !settings.ai.enabled) return false;

  // Не в эфире - не отвечаем. Проверка синхронная и потому читает не базу, а общий реестр
  // twitch/streamStatus.js, который наполняет опрос ActivitiTracker: до первого успешного опроса
  // там false, то есть неизвестный статус означает «офлайн», а не «отвечай». Отставание опроса
  // (минуты) здесь ничего не стоит - на границе эфира лишний или недоданный ответ безобиден.
  //
  // В debug-режиме проверка снимается - тем же приёмом и по той же причине, что у авто-отправок
  // в commands/CustomCommands.js: локальная проверка не должна требовать настоящего стрима.
  if (!botInitInfo.settings['debug'] && !streamStatus.isLive(broadcasterIdOf(channel))) return false;

  if (isBotSender(userState)) return false;

  // Ступень нулевая и единственная бесплатная целиком: сообщение из одних смайликов канала.
  // Раньше такое уходило в модель, она честно платила за «AROLF» и заводила на него заготовку в
  // AiFilter - то есть каждый смайлик стоил каналу вызова, а таблица заготовок набивалась шумом,
  // который ничему не учит. Ответить тем же смайликом можно и без модели: список смайликов
  // канала уже лежит в памяти процесса (db/chatStats.js), так что проверка синхронная, как и
  // всё остальное в tryAnswer.
  //
  // Молчание при неудачном броске окончательное, скриптовый хвост не зовётся: «да» в ответ на
  // смайлик - ровно та трата внимания, которую тут и убирают.
  //
  // Кулдаун этот путь не проверяет и собой не взводит, в отличие от ступеней ниже. Кулдаун
  // ограничивает трату, а тратить тут нечего; взводить его смайликом значило бы задержать на
  // пятнадцать секунд настоящий вопрос, заданный следом. Единственный тормоз здесь - бросок.
  const question = stripBotMention(message);
  const echo = emoteEcho(channel, question);
  if (echo) {
    const sent = Math.random() < EMOTE_REPLY_CHANCE;
    if (sent) client.say(channel, echo, userState['id']);
    // Пишется и молчание тоже: строка «ответ был бы такой, но не отправлен» - единственное, по
    // чему в панели видно, что путь работает и что доля отвеченных та самая. Не ожидается -
    // решение о том, берём ли мы сообщение, синхронное.
    aiStore
      .writeLog({
        channel,
        userId: String(userState['user-id']),
        login: userState['username'],
        question,
        answer: echo,
        source: 'emote',
        verdict: 'normal',
        billed: false,
        sent,
      })
      .catch((err) => console.error('[aiReply] emote log failed:', err.message));
    return true;
  }

  // Кулдаун один на канал: он ограничивает, как часто бот ГОВОРИТ, а не кто его спрашивает.
  if (!isTimerReady(lastAiReply.get(channel) || 0, cfg.cooldownMs)) return false;

  // Дневной лимит здесь НЕ проверяется, хотя раньше проверялся. Он ограничивает трату, а первые
  // три ступени пути (фильтр, кэш, тот же вопрос другими словами) не тратят ничего - отказывать
  // на входе значило бы молчать в ответ на вопрос, ответ на который уже лежит готовым. Проверка
  // стоит ниже, ровно перед вызовом модели, то есть перед единственным местом, где тратятся
  // деньги. Узнать заранее, найдётся ли готовый ответ, нельзя: это чтение из базы, а решение о
  // том, берём ли мы сообщение, синхронное.
  //
  // Claimed before the async work starts, so a burst of mentions in the same second produces one
  // answer rather than one per message.
  lastAiReply.set(channel, Date.now());
  answer(client, channel, userState, message, cfg, settings, scripted).catch((err) =>
    console.error('[aiReply] unhandled failure:', describeError(err))
  );
  return true;
}

async function answer(client, channel, userState, message, cfg, settings, scripted) {
  // Сообщение уже заявлено как наше, вернуть его в цепочку commands/msgHandle.js нельзя - она
  // давно отработала. Поэтому хвост цепочки передан сюда функцией и вызывается там, где нам
  // сказать нечего.
  const handOff = typeof scripted === 'function' ? scripted : () => {};
  const receivedAt = Date.now();
  const question = stripBotMention(message);
  const login = userState['username'];
  const base = { channel, userId: String(userState['user-id']), login, question };

  const send = (text) => {
    if (!text) return false;
    if (Date.now() - receivedAt > LATE_REPLY_MS) return false;
    client.say(channel, text, userState['id']);
    return true;
  };

  // 1. The global filter: messages already judged not worth an API call.
  const canned = await aiStore.findFilterAnswer(channel, question);
  if (canned) {
    const sent = send(canned);
    await aiStore.writeLog({ ...base, answer: canned, source: 'filter', verdict: 'normal', billed: false, sent });
    return;
  }

  // 2. This channel's cache of durable answers.
  const cached = await aiStore.findCachedAnswer(channel, question);
  if (cached) {
    const sent = send(cached);
    await aiStore.writeLog({ ...base, answer: cached, source: 'cache', verdict: 'normal', billed: false, sent });
    return;
  }

  // 3. Тот же вопрос, но другими словами. Проверка стоит здесь, а не в общем чтении ниже, чтобы
  // путь сохранял свою форму: каждая следующая ступень дороже предыдущей и выполняется, только
  // если предыдущая не ответила. Один индексный запрос перед вызовом модели ничего не стоит на
  // фоне её бюджета в несколько секунд.
  const answered = await aiStore.recentAnswers(channel, SIMILAR_SCAN_LIMIT);
  const similar = memoryRecall.findSimilarAnswer(question, answered);

  if (similar && similar.same) {
    const sent = send(similar.answer);
    // Формулировка кладётся в кэш как ещё один ключ к тому же ответу. Дальше её ловит точное
    // совпадение выше - то есть скан двухсот строк окупается один раз, а потом это обычный поиск
    // по индексу. Ответ уже был признан моделью долгоживущим, иначе его бы в кэше не было, и
    // другая формулировка того же вопроса не делает его менее долгоживущим.
    await aiStore.cacheAnswer(channel, question, similar.answer, ANSWER_CACHE_MAX);
    await aiStore.writeLog({
      ...base,
      answer: similar.answer,
      source: 'cacheSimilar',
      verdict: 'normal',
      billed: false,
      sent,
      similarTo: similar.text,
    });
    return;
  }

  // Дальше начинается платная часть, и только здесь дневной лимит вправе остановить ответ.
  // Готового ответа не нашлось, значит сказать нам нечего - сообщение возвращается тому хвосту
  // цепочки, который ответил бы на него без ИИ. Строка в журнале пишется всё равно: пока лимит
  // упирается, это единственное место, где видно, скольким он отказал, - то есть основание
  // поднять его или оставить как есть.
  if (!budgetAvailable(cfg.dailyRequestLimit)) {
    handOff();
    await aiStore.writeLog({
      ...base,
      answer: null,
      source: 'budget',
      verdict: 'normal',
      billed: false,
      sent: false,
    });
    return;
  }

  const broadcasterId = broadcasterIdOf(channel);
  const lines = (recentChat.get(channel) || []).slice();
  const people = chatParticipants(userState, lines);
  // Правила про мут по просьбе и два поля под него включаются ТОЛЬКО здесь и только вместе: по
  // ключевым словам в сообщении и только у того, кто вправе просить. У всех остальных модель и не
  // узнает, что такая возможность есть, - отказывать ей не в чем, а промт короче на две страницы.
  //
  // Следствие, которое стоит знать: отказ «не тому просящему» в журнал больше не пишется, потому
  // что его не существует - код просто не предлагает модели этой возможности. Видны только отказы,
  // которые код действительно вынес: неизвестный ник, защищённый адресат, просьба про себя.
  const banAsk = looksLikeBanRequest(question) && mayAskBan(channel, userState, login);
  // Один момент времени на весь запрос: тот же, что уйдёт в промт, сверяется потом с ответом.
  const askedAt = new Date();
  const nowText = describeNow(askedAt);
  // Решение о запрете RMT принимается ОДИН раз и отсюда расходится в обе половины - в правило,
  // которое читает модель, и в проверку ответа после неё. Считать его дважды значило бы разрешить
  // им разойтись.
  const [card, memory, stored, replies] = await Promise.all([
    broadcasterId ? aiStore.streamCard(broadcasterId) : Promise.resolve({ live: false }),
    aiStore.recentExchanges(channel, base.userId, cfg.memoryPairs),
    // Read even when self-writing is switched off: the switch governs what the bot may ADD, while
    // whatever an admin has put in the memory by hand is part of what the bot knows either way.
    aiStore.listMemory(channel, cfg.memoryMax),
    // Последние ответы бота в этом чате - ради их зачинов, см. recentOpenings. Всего канала, а не
    // этого зрителя: повторяющийся заход виден чату целиком, а не каждому по отдельности.
    aiStore.recentReplies(channel, RECENT_REPLIES_SCAN),
  ]);
  const allowed = allowedMentionLogins(question, lines);
  const rmtRestrict = rmtRestricted(channel, card);

  // Хранилище и промт - разные величины. memoryMax ограничивает, сколько канал ПОМНИТ,
  // memoryRecall - сколько уходит в оплачиваемый запрос; отбор по словам вопроса делает
  // shared/memoryRecall.js. Строки, добавленные админом руками, идут в запрос всегда: их немного,
  // они написаны как постоянное утверждение о канале, и они же не подлежат ротации - отбирать их
  // по словам значило бы прятать от модели то, что человек велел ей знать.
  const manual = stored.filter((f) => f.source !== 'ai');
  const learned = stored.filter((f) => f.source === 'ai');
  const facts = manual
    .concat(memoryRecall.rankFacts(question, learned, cfg.memoryRecall))
    .sort((a, b) => new Date(a.createdAt) - new Date(b.createdAt));
  // Список один, и номер в поле forget разбирается ровно по нему.
  const numbered = facts;

  let res;
  const startedAt = Date.now();
  try {
    res = await aiProvider.ask({
      model: cfg.model,
      maxTokens: MAX_TOKENS,
      timeoutMs: cfg.requestTimeoutMs,
      tool: banAsk ? ANSWER_TOOL_WITH_BAN : ANSWER_TOOL,
      system: buildSystemPrompt(cfg),
      user: buildUserContent({
        channel,
        question,
        login,
        now: nowText,
        role: describeRole(userState),
        card,
        rmtRestrict,
        banAsk,
        cheatsheet: settings.ai.cheatsheet,
        tone: settings.ai.tone,
        memory,
        facts,
        emotes: emotesInQuestion(channel, question),
        similar,
        allowed,
        openings: recentOpenings(replies),
        chat: chatContext(lines, login, message),
      }),
    });
    healthTracker.reportSuccess('ai-reply', { label: 'AI-ответы на упоминания', scope: channel });
  } catch (err) {
    // Every network-facing subsystem here recovers by itself, so one failed call is not an
    // incident - healthTracker holds it for the grace window and only then calls it one.
    healthTracker.reportFailure('ai-reply', {
      label: 'AI-ответы на упоминания',
      detail: describeError(err),
      scope: channel,
      graceMs: HEALTH_GRACE_MS,
    });
    // Зритель всё равно получает ответ - тот самый, который получил бы с выключенной фичей.
    // Раньше здесь слалась отговорка напрямую, мимо «да/нет» на вопрос и мимо обоих выключателей
    // с кулдаунами; хвост цепочки знает про них все, поэтому зовём его, а не повторяем половину.
    // В журнал уходит answer: null - сказанное хвостом не является ответом ИИ и не должно
    // попадать в колонку, по которой судят о качестве ответов модели.
    handOff();
    await aiStore.writeLog({
      ...base,
      answer: null,
      source: 'error',
      verdict: 'normal',
      billed: false,
      sent: false,
      error: describeError(err),
    });
    return;
  }

  billedToday += 1;

  // Принудительный вызов инструмента делает поля ожидаемой формой ответа, но отказ и обрыв по
  // потолку токенов приезжают обычным 200, в котором нет ничего пригодного, - проверяем, а не
  // предполагаем, потому что иначе этот отказ молчаливый.
  const out = res.fields;
  const rawReply = out ? out.reply : res.text;

  const reply = sanitizeReply(rawReply, allowed, channel, rmtRestrict);
  const verdict = out && out.verdict ? out.verdict : 'normal';
  const reason = sanitizeReason(out ? out.reason : '');
  const usage = res.usage;

  // ЗА ЧТО МОДЕЛЬ НАКАЗЫВАЕТ, НА ТО ОНА НЕ ОТВЕЧАЕТ. Признак таких сообщений сформулирован в
  // правилах так: убери его из чата, и не пропадёт ничего, - а раз отвечать не на что, то и любая
  // реплика в ответ есть та самая реакция, ради которой сообщение написано. Остроумный отказ
  // добивается её лучше всего: он показывает, что провокация сработала. Молчит и скриптовый
  // хвост - случайное «да» вместо ответа модели было бы тем же кормлением, только глупее.
  // Наказание при этом идёт своим чередом ниже, и строка в журнале пишется как обычно (sent:
  // false, ответ модели в колонке ответа), так что решение видно на сайте, а не только в чате.
  //
  // ИСКЛЮЧЕНИЕ ОДНО - ПРЕДУПРЕЖДЕНИЕ, и правило оно не отменяет. Молчание работает, когда за ним
  // сразу следует мут: тогда «ответа нет» и есть ответ. Когда наказание отложено (отношение к
  // автору ещё позволяет), молчание не значит ничего вообще - зритель видит, что бот промолчал, и
  // ровно то же самое он видел бы, если бы фича была выключена. Предупреждение говорится вслух
  // именно потому, что оно должно быть замечено до того, как станет мутом.
  //
  // Пустой ответ после очистки - другой случай: сказать нечего, но и повода наказывать нет, и
  // зритель не должен остаться вообще без реакции. Раньше в такой ситуации в чат уходил мусор,
  // так что молчание было незаметно; после отбраковки разметки этот случай стал реальным, и он
  // ведёт туда же, куда падение API.
  // ТАЙМ-АУТ ПО СОБСТВЕННОЙ ПРОСЬБЕ разбирается ДО наказания, потому что он его отменяет. Зритель
  // просит замутить самого себя - это игра, и обходится она с наказанием ровно наоборот: ответ
  // уходит в чат, а срок выдаётся вдвое больше запрошенного.
  const selfAsked = selfTimeoutSeconds(out ? out.selfTimeout : '');

  // Наказывает ТОЛЬКО вердикт. Раньше решение делили вердикт и шкала отношения (терпение перед
  // первым мутом, множитель срока, наказание по дну шкалы за минус без вердикта); шкалы больше
  // нет, поэтому вердикт timeout мутит сразу и на плоский срок из настроек.
  const wouldPunish = verdict === 'timeout' ? 'timeout' : null;
  const punishAction = selfAsked ? null : wouldPunish;

  // Считается всегда, потому что нужно обеим веткам: одной как решение, другой как ПОЛ для срока.
  // Без этого пола просьба «замуть меня на секунду» становилась бы способом откупиться от
  // десятиминутного мута секундным.
  const wouldSeconds = wouldPunish === 'timeout' ? cfg.timeoutSeconds : 0;
  const punishSeconds = punishAction === 'timeout' ? wouldSeconds : null;
  // Просить можно больше, но не меньше: пол - это то, что человек и так бы получил.
  const selfSeconds = selfAsked ? Math.max(selfAsked, wouldSeconds) : 0;

  // ЗДЕСЬ БОЛЬШЕ НЕТ ПРОВЕРКИ ИСТОЧНИКА, и это дыра с известным размером. Пока шкала была, порог
  // доверия не пускал в память тех, кто внизу: на живых данных из 45 фактов канала 16 оказались
  // выдумками двух зрителей со счётом −8 и ниже («стример стал мэром одессы», «в PoE использует
  // клиент с подкруткой лута»), посаженными правдоподобно и первыми. Правило промта «верь, если
  // правдоподобно и не спорит с записанным» такое не ловит - проверить сказанное не обо что.
  // Со шкалой ушёл и порог, так что учить бота снова может кто угодно, а мест в памяти теперь
  // десять, а не сотня. Заменой может быть роль автора (стример/модератор), но это другое решение,
  // и принимать его молча тут нельзя.

  // ЗА ЧТО НАКАЗЫВАЕМ, НА ТО НЕ ОТВЕЧАЕМ. Предупреждения больше нет: оно держалось на шкале
  // отношения, а без неё «первое нарушение» от «десятого» не отличить.
  const silent = Boolean(punishAction);
  const sent = reply && !silent ? send(reply) : false;
  if (!reply && !silent) handOff();

  let punished = false;
  let selfTimedOut = false;
  if (punishAction && !isProtected(userState)) {
    // Observe mode is the default and stays until the journal says the model's calls are worth
    // acting on. The row is written either way, which is what makes that comparison possible.
    if (
      cfg.punishMode === 'enforce' &&
      punishAction === 'timeout' &&
      !replyIfBotLacksMod(client, channel, userState, settings)
    ) {
      Twitch_ban_API.timeout(
        userState['user-id'],
        punishSeconds,
        userState['room-id'],
        reason || 'глупый вопрос'
      );
      punished = true;
    }
    // Ветка `else if`, а не отдельная проверка: наказанное сообщение не должно попутно завести
    // заготовку. Заготовка отвечает навсегда и без модели, и меньше всего ей подходит текст, за
    // который человека только что замутили.
  } else if (selfSeconds && !isProtected(userState)) {
    // Просьба исполняется в том же режиме, что и наказание: в observe бот не трогает никого, и
    // строка в журнале - единственное, что происходит. Мод и VIP исключены не из вежливости - их
    // Twitch замутить всё равно не даст, и попытка вернулась бы ошибкой вместо шутки.
    if (cfg.punishMode === 'enforce' && !replyIfBotLacksMod(client, channel, userState, settings)) {
      Twitch_ban_API.timeout(
        userState['user-id'],
        selfSeconds,
        userState['room-id'],
        'по собственной просьбе'
      );
      selfTimedOut = true;
    }
  } else if (verdict === 'filter' && !selfSeconds && !muteAsk) {
    // The answer it just gave becomes the canned one, so the same message never costs again.
    // Фильтр вечный, поэтому сиюминутному там не место тем более, чем в кэше.
    //
    // И ТОТ ЖЕ ПОРОГ ДОВЕРИЯ, ЧТО У ПАМЯТИ. Заготовка отвечает всем и навсегда, а пишется она в
    // тоне того разговора, в котором родилась: ответ, написанный «суше» для человека с минусом, -
    // плохой вечный ответ незнакомцу. На живых данных так завелись строки «запомни, ты сосал» →
    // «Хорошо, запомнил, что ты сосал ahahah» и «привет, как дела?» → «Привет, лучший друг!»,
    // которая зовёт лучшим другом кого угодно. Согласование в панели (approved) - вторая половина
    // этой же защиты, и нужны обе: порог отсекает происхождение, согласование - содержание.
    if (!quotesVolatile(reply, volatileValues(card, askedAt))) {
      await aiStore.addFilterEntry(channel, question, reply);
    }
  }

  // МУТ ДРУГОМУ ЧЕЛОВЕКУ ПО ПРОСЬБЕ. Стоит отдельно от цепочки выше, а не веткой в ней: та целиком
  // про автора сообщения - его наказывают, его просьбу о себе исполняют, его ответ идёт в заготовки.
  // Здесь адресат другой, и с наказанием у этого действия общего только эндпоинт: бот не судит ни
  // того, кого мутят, ни его сообщений - он выполняет просьбу того, кому это позволено.
  let mutedUser = null;
  let muteDone = false;
  let muteRefused = null;
  const muteAsk = banAsk ? requestedMute(out) : null;
  if (muteAsk) {
    // Сообщение, за которое наказывают самого просящего, ничьих просьб не исполняет: нельзя одной
    // строкой нахамить и распорядиться.
    const target = punishAction ? null : await resolveSubject(channel, muteAsk.name, people);
    if (punishAction) muteRefused = 'punished';
    // Ника нет на канале - мутить некого: resolveSubject требует, чтобы человек здесь писал, и это
    // ровно та проверка, которая не даёт замутить случайного человека из соседнего чата.
    else if (!target) muteRefused = 'unknown';
    else if (target.userId === base.userId) muteRefused = 'self';
    else if (peerProtected(channel, target)) muteRefused = 'protected';
    else {
      mutedUser = target.login;
      // Режим тот же, что у наказания: в observe строка в журнале - единственное, что происходит.
      // Результат дожидается, в отличие от наказания выше: ответ зрителю уже ушёл, задержки никто
      // не увидит, а «выдан ли мут на самом деле» - это половина того, ради чего строка пишется.
      if (cfg.punishMode === 'enforce' && !replyIfBotLacksMod(client, channel, userState, settings)) {
        // Причина уезжает в текст мута, а оттуда - в ModeratorActionLogs: владелец канала этот
        // раздел панели не видит вовсе, и «по просьбе такого-то» там единственный способ понять,
        // откуда взялся мут от бота.
        muteDone = await Twitch_ban_API.timeout(
          target.userId,
          muteAsk.seconds,
          userState['room-id'],
          'по просьбе ' + login
        );
      }
    }
  }

  // Кэшируется не всё, что модель назвала долговечным: ответ не должен цитировать сиюминутное.
  // Модель пометила `eternal` 162 ответа из 201 - она применяет метку слишком щедро, и с
  // появлением даты в промте вечных «сейчас 2026 год» стало бы много. Здесь решает не её оценка, а
  // совпадение текста с тем, что мы сами подставили.
  //
  // УСЛОВИЕ «ВОПРОС ЗАДАН НЕ В ПЕРВЫЙ РАЗ» СНЯТО. Оно стояло по замеру: кэш из 153 строк сработал
  // за всё время 2 раза, потому что пополнялся почти на каждом вызове, а вопросы в чате почти все
  // уникальные. Тот замер снят с кэша, у которого было только точное совпадение по aiTextKey - то
  // есть по регистру и пробелам. С тех пор появился поиск похожего (shared/memoryRecall.js): одна
  // строка в кэше отвечает теперь не на одну формулировку, а на весь класс вопросов с тем же
  // набором значимых слов. При этом само условие требовало ДОСЛОВНОГО повтора, и в живом чате оно
  // не выполнялось почти никогда: вопрос про любимую музыку, заданный четыре раза четырьмя
  // формулировками, - это четыре разных ключа со счётчиком ноль у каждого, четыре вызова модели и
  // пустой кэш. Условие, которое должно было отсеивать одноразовые вопросы, отсеивало и
  // повторяющиеся тоже, потому что считало не то.
  //
  // Возражение «кэш станет свалкой» осталось в силе и закрыто там, где ему место, - потолком с
  // вытеснением по последнему обращению (ANSWER_CACHE_MAX, ротация в db/aiStore.js). Строка,
  // которую ни разу не спросили повторно, уходит сама; та, которую спрашивают, остаётся.
  // ПОКАЗАННАЯ ЗАГОТОВКА МОЖЕТ ОКАЗАТЬСЯ УСТАРЕВШЕЙ, И СКАЗАТЬ ОБ ЭТОМ УМЕЕТ ТОЛЬКО МОДЕЛЬ. Точное
  // попадание в кэш отвечает вообще без вызова, поэтому подсказка «об этом уже спрашивали» - это
  // единственный момент, когда прошлый ответ кому-то показан и его вообще можно оспорить. Строка
  // без этого живёт, пока её не вытеснит ротация или не удалит человек в панели, - а вопросы,
  // ответ на которые меняется («во сколько стрим», «что за игра»), спрашивают как раз чаще всего.
  //
  // Стоит ПЕРЕД записью в кэш ниже, и это не вкусовщина: удаление ищет строки по тексту ответа, и
  // если бы новый ответ успел лечь в кэш до починки, он мог бы попасть под своё же удаление.
  //
  // Вердикт тот же, что и у памяти: сообщением, за которое модель просит тайм-аут, кэш не правят.
  // Провокация не должна получать право стирать чужие ответы. Наказание по дну шкалы приходит без
  // вердикта, поэтому смотрим и на него: право стирать чужие ответы даёт не форма решения, а то,
  // наказали ли за это сообщение.
  let cacheFix = null;
  if (similar && out && verdict === 'normal' && !punishAction) {
    const action = String(out.staleAnswer || '').trim();
    // Замена проходит ту же очистку, что и ответ в чат, потому что уходить ей именно туда - и не
    // один раз, а на каждый повтор того вопроса. Если очистка съела текст целиком, остаётся
    // удаление: строка уже объявлена неверной, и оставить её из-за негодной замены значит не
    // сделать ничего.
    const cleaned = action === 'replace' ? sanitizeReply(out.fixedAnswer, allowed, channel, rmtRestrict) : '';
    const replacement = cleaned.length >= MIN_FIXED_ANSWER_CHARS ? cleaned : '';
    if (action === 'delete' || action === 'replace') {
      const fixed = await aiStore.fixCachedAnswer(channel, similar.answer, replacement);
      if (fixed) cacheFix = replacement ? 'replace' : 'delete';
    }
  }

  // В КЭШ ИДЁТ НЕ ВЕСЬ ОТВЕТ, А ЕГО УТВЕРДИТЕЛЬНАЯ ЧАСТЬ. Характер заставляет бота почти всегда
  // заканчивать встречным вопросом, а переиспользованное любопытство выглядит фальшиво - раньше
  // из-за этого модели было велено помечать такой ответ временным, и на живых данных это убивало
  // кэш целиком: 92% ответов temporary, 2 попадания на 246 обращений за день. Но временный там
  // только хвост, факт в начале долговечен, и отрезать хвост - работа кода, а не инструкции
  // (shared/cacheableAnswer.js). Пустой остаток означает, что утверждения в ответе нет вовсе, -
  // такой ответ не кэшируется, и это правильный исход, а не потеря.
  //
  // Ответ на сообщение, которое чему-то научило, не кэшируется вообще: повтор из кэша обещает
  // запомнить и ничего не запоминает. Одно из двух попаданий кэша за день было ровно таким.
  let cachedNow = false;
  // Ответ на просьбу о муте не кэшируется по той же причине: из кэша он бодро обещает мут, которого
  // не будет.
  const cacheText =
    out && !selfSeconds && !muteAsk && !cacheableAnswer.promisesAction(out.remember)
      ? cacheableAnswer.withoutTail(reply)
      : '';
  if (
    verdict === 'normal' &&
    !punishAction &&
    out &&
    out.cacheable === 'eternal' &&
    cacheText &&
    !quotesVolatile(cacheText, volatileValues(card, askedAt))
  ) {
    cachedNow = await aiStore.cacheAnswer(channel, question, cacheText, ANSWER_CACHE_MAX);
  }

  // Отметка «эти факты сейчас пригодились» - ею ротация в db/aiStore.js выбирает, что вытеснить,
  // когда хранилище упрётся в потолок. Не ожидается: ответ зрителю уже ушёл, и задержка здесь
  // ничего не стоит, а падение - тем более не должно ронять разбор ответа модели.
  aiStore.touchFacts(channel, facts.map((f) => f.key));

  // Memory is written only from a message the model itself called ordinary. A message it wants to
  // time out or to file away as noise is not a source to learn the channel from, and reusing the
  // verdict here costs nothing - it has already been decided.
  //
  // ПАМЯТЬ ОДНА. Раньше их было две - про канал и про людей, - и адресат факта решал, в какую он
  // уйдёт; вместе с ними ушли поиск человека по нику, чтение по пулу каналов и вторая нумерация в
  // промте. Факт про зрителя теперь просто факт: «parovoz24 делает нарезки» стоит в том же списке,
  // что «стрим начинается в 19:00», и ищется тем же отбором по словам вопроса.
  let remembered = null;
  let forgot = null;
  if (out && verdict === 'normal' && !punishAction) {
    const fact = sanitizeFact(out.remember);
    const meta = {
      authorLogin: login,
      authorUserId: base.userId,
      authorRole: roleKey(userState),
      sourceMessage: question,
      // Слова, по которым факт потом искать. Считаются даже когда факта нет: пустой список стоит
      // дешевле развилки, а без факта он никуда и не уйдёт.
      keywords: sanitizeKeywords(out.rememberKeys),
    };
    if (fact && cfg.memoryEnabled) {
      if (await aiStore.rememberFact(channel, fact, meta, cfg.memoryMax)) remembered = fact;
    }
    // The number refers to the list built above, so an answer that arrives after the memory has
    // changed can only ever drop a fact that was actually on the numbered list it read.
    const index = parseInt(String(out.forget || '').trim(), 10);
    if (Number.isInteger(index) && index >= 1 && index <= numbered.length) {
      const target = numbered[index - 1];
      if (await aiStore.forgetFact(channel, target.key)) forgot = target.fact;
    }
  }

  await aiStore.writeLog({
    ...base,
    answer: reply,
    source: 'model',
    verdict,
    reason,
    cacheable: out ? out.cacheable : null,
    // Ушёл ли ответ в кэш на самом деле. Без этого поля «вечный» в журнале ничего не обещает:
    // сиюминутную цитату отсеивает уже наша проверка, и по строке журнала не было видно, кто из
    // двоих решил - модель или она.
    cached: cachedNow,
    billed: true,
    sent,
    punished,
    remembered,
    forgot,
    // Что показали модели как «об этом уже спрашивали». В журнале это единственный способ увидеть,
    // срабатывает ли подсказка и на чём именно - у нестрогого сравнения нет другого зеркала.
    similarTo: similar ? similar.text : null,
    // Что модель сделала с показанной заготовкой: delete, replace или пусто. Вместе с similarTo это
    // единственное место, где видно, что кэш поправила именно она, - самой строки в кэше после
    // удаления уже нет, а после замены она выглядит как обычная.
    cacheFix,
    protectedUser: isProtected(userState),
    // Наказание и его срок. В журнал уходят и в observe: иначе не видно, каким был бы мут, а это
    // и есть основание переводить режим в enforce.
    punishAction,
    timeoutSeconds: punishSeconds,
    // Тайм-аут по собственной просьбе: сколько выдано и выдано ли на самом деле. Отдельно от
    // punishAction намеренно - это не наказание, и в подсчёте наказаний ему делать нечего.
    selfTimeout: selfSeconds || null,
    selfTimedOut,
    // Мут по просьбе о другом человеке: кого, на сколько, вышло ли и почему не вышло. Отказ
    // пишется тоже - просьбы, которые код не пропустил, не видны больше нигде.
    mutedUser,
    muteSeconds: muteAsk ? muteAsk.seconds : null,
    muteDone,
    muteRefused,
    model: cfg.model,
    inputTokens: usage.inputTokens,
    outputTokens: usage.outputTokens,
    cacheReadTokens: usage.cacheReadTokens,
    // Запись в кэш раньше не сохранялась вообще, а стоит она дороже обычного входа. Без этого
    // поля вызов с промахом мимо кэша нельзя отличить от вызова без кэша вовсе. У поставщика с
    // неявным кэшем ставить её нечем, и поле приезжает пустым - это не промах, а отсутствие платы.
    cacheWriteTokens: usage.cacheWriteTokens,
    costUsd: aiProvider.costUsd(cfg.model, usage),
    latencyMs: Date.now() - startedAt,
  });
}

